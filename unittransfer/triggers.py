def mod_operands(mod) -> Dict[str, List[str]]:
    """The operand lists that are a property of THIS mod, not of the engine.

    Everything here comes from a parse the toolkit already owns — trait and
    ancillary names off the same pass that read the triggers, factions and
    cultures from the buildings layer, building levels from the EDB. Nothing is
    re-parsed, and nothing is hardcoded per mod.
    """
    out: Dict[str, List[str]] = {"traits": [], "ancillaries": [], "factions": [],
                                 "cultures": [], "buildings": []}
    if mod is None:
        return out
    for attr, keyword, key in (("edct_path", "Trait", "traits"),
                               ("eda_path", "Ancillary", "ancillaries")):
        path = getattr(mod, attr, None)
        if path is None or not path.exists():
            continue
        try:
            tf = parse_file(path)
        except OSError:
            continue
        out[key] = sorted(set(tf.definitions.get(keyword, [])))
    try:
        out["factions"] = sorted(mod.faction_cultures)
        out["cultures"] = sorted(set(mod.faction_cultures.values()))
    except (OSError, ValueError):
        pass
    try:
        levels = []
        for bl in mod.edb.buildings:
            levels.append(bl.name)
            levels.extend(b.name for b in bl.blocks)
        out["buildings"] = sorted(set(levels))
    except (OSError, ValueError, AttributeError):
        pass
    return out


def vocab_payload(mod=None) -> Dict:
    """Everything the trigger builder needs: the engine's vocabulary + this mod's.

    The engine half is the generated file, identical for every mod. The mod half
    is what its own traits, ancillaries, factions, cultures and buildings are
    called, so a picker offers names that exist here rather than vanilla's.
    """
    v = vocab()
    return {
        "conditions": v.get("conditions", []),
        "events": v.get("events", []),
        "operators": v.get("operators", list(OPS)),
        "attributes": v.get("attributes", []),
        "operand_sources": OPERAND_SOURCES,
        "operands": dict(mod_operands(mod), attributes=v.get("attributes", [])),
        "source": v.get("source", {}),
        "mod": getattr(mod, "name", ""),
    }


def block_spans(block: str) -> Dict[str, List[List[int]]]:
    """``{label: [[first, last]]}``, 1-based, for one trigger block."""
    trig = parse_block(block if block.endswith("\n") else block + "\n")
    spans: Dict[str, List[List[int]]] = {"name": [[trig.start + 1, trig.start + 1]]}
    if trig.wtt_line >= 0:
        spans["when_to_test"] = [[trig.wtt_line + 1, trig.wtt_line + 1]]
    for i, c in enumerate(trig.conditions):
        spans[f"condition#{i + 1}"] = [[c.line + 1, c.line + 1]]
    for i, e in enumerate(trig.effects):
        spans[f"effect#{i + 1}"] = [[e.line + 1, e.line + 1]]
    return spans


def block_fields(block: str) -> List[Tuple[str, str]]:
    """``[(label, value)]`` for one block, in the order the lines appear."""
    trig = parse_block(block if block.endswith("\n") else block + "\n")
    out = [("name", trig.name)]
    if trig.wtt_line >= 0:
        out.append(("when_to_test", trig.when_to_test))
    for i, c in enumerate(trig.conditions):
        out.append((f"condition#{i + 1}", c.text().strip()))
    for i, e in enumerate(trig.effects):
        out.append((f"effect#{i + 1}", " ".join([e.keyword] + e.args)))
    return out
